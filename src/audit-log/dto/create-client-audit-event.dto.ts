import {
  IsString,
  IsNotEmpty,
  IsOptional,
  IsEnum,
  ValidateNested,
} from 'class-validator';
import { Type } from 'class-transformer';
import {
  AuditActionType,
  AuditClientApp,
  AuditStatus,
} from '../audit-log.types';
import { AuditDiffPayloadDto } from './audit-diff.dto';

export class CreateClientAuditEventDto {
  // ─── Business References ───

  @IsOptional()
  @IsString()
  trackingCode?: string; // Optional: auto-generated by backend if omitted

  @IsOptional()
  @IsString()
  correlationId?: string;

  // ─── Target Resource ───

  @IsString()
  @IsNotEmpty()
  targetDepartmentId!: string; // e.g., "hr", "ats", "construction"

  @IsString()
  @IsNotEmpty()
  resourceSlug!: string; // e.g., "leave_request", "ats_jobs"

  @IsString()
  @IsNotEmpty()
  resourceLabel!: string; // e.g., "Phê duyệt", "Tuyển dụng"

  @IsString()
  @IsNotEmpty()
  targetEntityId!: string; // e.g., "job-struct-eng-01"

  @IsOptional()
  @IsString()
  targetProjectId?: string;

  // ─── Action & Narrative ───

  @IsEnum(AuditActionType)
  actionType!: AuditActionType;

  @IsString()
  @IsNotEmpty()
  actionLabel!: string; // e.g., "Phê duyệt", "Tạo mới"

  @IsEnum(AuditStatus)
  status!: AuditStatus;

  @IsString()
  @IsNotEmpty()
  summary!: string; // e.g., "Tạo mới Job Description cho vị trí Kỹ sư kết cấu cao cấp"

  @IsOptional()
  @IsString()
  failureReason?: string;

  // ─── Diff & Snapshots ───

  @ValidateNested()
  @Type(() => AuditDiffPayloadDto)
  diffPayload!: AuditDiffPayloadDto;

  @IsOptional()
  snapshotBefore?: Record<string, unknown>;

  @IsOptional()
  snapshotAfter?: Record<string, unknown>;

  // ─── Client Context ───

  @IsOptional()
  @IsEnum(AuditClientApp)
  clientApp?: AuditClientApp = AuditClientApp.WEB_PORTAL;

  @IsString()
  @IsNotEmpty()
  requestUrl!: string; // Current client route (e.g., "/vi/ats/jobs-management")
}
